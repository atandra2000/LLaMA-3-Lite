"""Generate ``VOICEOVER_SCRIPT.md`` from ``narration.yaml`` + ``facts.json``.

The Markdown script is a build artifact: narration lives in ``narration.yaml``
and every number comes from ``facts.json``, so the document cannot drift from
either source. Timing columns appear once ``audio/timings.json`` exists
(Phase 2); until then they are derived from the whole-section
``audio/durations.json`` and marked *planned*.

Usage:
    python tools/build_script_doc.py            # write the doc
    python tools/build_script_doc.py --check    # exit 1 if the doc is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

try:  # imported as ``tools.build_script_doc``
    from tools.lint_script import word_count
except ImportError:  # run as ``python tools/build_script_doc.py``
    from lint_script import word_count

HERE = Path(__file__).resolve().parent
V2 = HERE.parent
OUT = V2 / "VOICEOVER_SCRIPT.md"
NARRATION = V2 / "narration.yaml"
FACTS = V2 / "facts.json"
DURATIONS = V2 / "audio" / "durations.json"
TIMINGS = V2 / "audio" / "timings.json"

VOICE_NOTE = ("Production: neural TTS narration (Edge TTS), scenes rendered with "
              "Manim (Typst-typeset math), assembled and loudness-normalised with "
              "ffmpeg.")


def mmss(seconds: float) -> str:
    minutes, rest = divmod(max(seconds, 0.0), 60)
    return f"{int(minutes)}:{rest:04.1f}"


def spec_rows(facts: dict) -> list[tuple[str, str]]:
    spec = facts["spec"]
    vocab = facts["vocab_label"]
    rows = [
        ("Parameters (total)", f"{facts['params_label']} ({facts['params']:,})"),
        ("Decoder blocks", f"{spec['n_layers']}"),
        ("Model dimension `d_model`", f"{spec['d_model']:,}"),
        ("Query heads", f"{spec['n_heads']}"),
        ("KV heads (GQA)", f"{spec['n_kv_heads']}"),
        ("Head dimension", f"{spec['head_dim']}"),
        ("FFN dimension `d_ff`", f"{spec['d_ff']:,}"),
        ("Vocabulary", vocab),
        ("Context `seq_len`", f"{spec['seq_len']:,}"),
        ("RoPE θ", f"{spec['rope_theta']:,.0f}"),
        ("Norms", f"RMSNorm pre-norm (ε = {spec['rms_norm_eps']:g})"
                  + (" + QK-norm" if spec["qknorm"] else "")),
        ("FFN activation", "SwiGLU"),
        ("Biases", "none"),
        ("Weight tying", "none (separate output head)"),
    ]
    return rows


def section_windows(doc: dict, durations: dict, timing: dict) -> dict[str, tuple[float, float]]:
    """Start/end for each section, from measured narration plus lead/tail."""
    windows: dict[str, tuple[float, float]] = {}
    clock = 0.0
    for section in doc["sections"]:
        measured = durations.get(section["id"])
        if measured is None:
            return {}
        budget = measured + timing["lead"] + timing["tail"]
        windows[section["id"]] = (clock, clock + budget)
        clock += budget
    return windows


def render(doc: dict, facts: dict, durations: dict, timings: dict) -> str:
    timing = doc["timing"]
    windows = section_windows(doc, durations, timing)
    sentences = sum(len(s["sentences"]) for s in doc["sections"])

    lines: list[str] = []
    add = lines.append
    add(f"# {doc['title']}")
    add("")
    add("**Voiceover script for the motion-graphics explainer video**")
    add(f"_Generated by `tools/build_script_doc.py` from `narration.yaml` and "
        f"`facts.json` — edit those, not this file._")
    add("")
    if windows:
        planned = sum(end - start for start, end in windows.values())
        basis = ("measured per-sentence `audio/timings.json`" if timings
                 else "planned from `audio/durations.json`")
        add(f"Runtime: **{mmss(planned)}** across {len(doc['sections'])} scenes "
            f"({timing['lead']:.2f} s lead + {timing['tail']:.2f} s tail each; {basis}).")
    add(f"Voice `{doc['voice']}`, rate `{doc['rate']}`. {VOICE_NOTE}")
    add("")
    add("| Spec | Value |")
    add("|---|---|")
    for label, value in spec_rows(facts):
        add(f"| {label} | {value} |")
    add("")
    add(f"Every number above is read from `facts.json`, which is built from `config.py` "
        f"and the LLaMA-3 tokenizer and gated by `tools/check_facts.py`. "
        f"{sentences} sentences; longest is "
        f"{max(word_count(s['text']) for sec in doc['sections'] for s in sec['sentences'])} words.")
    add("")
    add("---")
    add("")

    for section in doc["sections"]:
        window = windows.get(section["id"])
        suffix = f"  *({mmss(window[0])} – {mmss(window[1])})*" if window else ""
        add(f"## {section['number']} · {section['title']}{suffix}")
        add("")
        narration = " ".join(s["text"].strip() for s in section["sentences"])
        add(f"> {narration}")
        add("")
        add(f"**On screen:** {section['screen'].strip()}")
        add("")
        add("**Cues**")
        add("")
        for sentence in section["sentences"]:
            when = timings.get("sentences", {}).get(sentence["id"])
            stamp = f" `{mmss(when['start'])}–{mmss(when['end'])}`" if when else ""
            add(f"- `{sentence['id']}`{stamp} — {sentence['visual'].strip()}")
        add("")

    add("---")
    add("")
    add(f"*{sentences} sentences, "
        f"{sum(word_count(s['text']) for sec in doc['sections'] for s in sec['sentences'])} words. "
        f"Build pipeline: `generate_audio.py` → `render_scenes.py` → `build_full_video.py` "
        f"(see `README.md`).*")
    add("")
    return "\n".join(lines)


def build() -> str:
    doc = yaml.safe_load(NARRATION.read_text(encoding="utf-8"))
    facts = json.loads(FACTS.read_text(encoding="utf-8"))
    durations = (json.loads(DURATIONS.read_text(encoding="utf-8"))
                 if DURATIONS.exists() else {})
    timings = json.loads(TIMINGS.read_text(encoding="utf-8")) if TIMINGS.exists() else {}
    return render(doc, facts, durations, timings)


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current == text:
            print(f"{OUT.name} is up to date")
            return 0
        print(f"{OUT.name} is STALE — run python tools/build_script_doc.py")
        return 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(V2.parent.parent)} "
          f"({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
